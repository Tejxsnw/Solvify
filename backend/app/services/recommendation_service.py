from typing import List
from app.schemas.financial import FinancialRatios, RecommendationItem, FinancialInput

class RecommendationService:
    @staticmethod
    def generate_recommendations(data: FinancialInput, ratios: FinancialRatios) -> List[RecommendationItem]:
        recommendations: List[RecommendationItem] = []

        # 1. Cash Flow & Debt Service
        if ratios.operating_cash_flow_to_debt < 0.15:
            recommendations.append(RecommendationItem(
                id="rec-cf-1",
                category="Cash Flow",
                priority="High" if ratios.operating_cash_flow_to_debt < 0.05 else "Medium",
                title="Improve Operating Cash Flow Coverage",
                metric="Operating Cash Flow / Debt",
                current_value=ratios.operating_cash_flow_to_debt,
                target_value=0.25,
                rationale="Cash flow generated by core business operations is insufficient to comfortably service existing debt principal and obligations.",
                action_plan=[
                    "Accelerate receivables collection by offering 2% early payment discounts (e.g. 2/10 net 30).",
                    "Renegotiate vendor payment terms from 30 days to 45-60 days where possible without penalty.",
                    "Halt non-essential capital expenditure projects until operating cash reserves stabilize."
                ]
            ))

        # 2. Leverage & Solvency
        if ratios.debt_to_equity > 2.0 or ratios.equity_ratio < 0.25:
            recommendations.append(RecommendationItem(
                id="rec-solv-1",
                category="Leverage",
                priority="High",
                title="De-leverage Balance Sheet & Restructure Debt",
                metric="Debt-to-Equity Ratio",
                current_value=ratios.debt_to_equity,
                target_value=1.50,
                rationale="Excessive debt relative to equity capital strains solvency and exposes the firm to refinancing risk and interest spikes.",
                action_plan=[
                    "Refinance high-interest short-term debt into lower fixed-rate long-term facilities.",
                    "Explore equity injection, mezzanine financing, or retained earnings retention instead of dividend payouts.",
                    "Monetize non-core underutilized assets to pay down senior credit facilities."
                ]
            ))

        # 3. Liquidity & Working Capital
        if ratios.current_ratio < 1.30:
            recommendations.append(RecommendationItem(
                id="rec-liq-1",
                category="Liquidity",
                priority="High" if ratios.current_ratio < 1.0 else "Medium",
                title="Replenish Working Capital & Quick Liquidity",
                metric="Current Ratio",
                current_value=ratios.current_ratio,
                target_value=1.60,
                rationale="Current assets barely cover near-term obligations, risking cash crunch in the event of customer delays or sudden cost shocks.",
                action_plan=[
                    "Establish a backup revolving credit facility to bridge seasonal working capital gaps.",
                    "Liquidate slow-moving inventory items to free up trapped operating cash.",
                    "Implement weekly 13-week rolling cash flow forecasting."
                ]
            ))

        # 4. Profitability & Margins
        if ratios.net_margin_pct < 5.0 or ratios.operating_margin_pct < 8.0:
            recommendations.append(RecommendationItem(
                id="rec-prof-1",
                category="Profitability",
                priority="Medium",
                title="Optimize Operating Margins & Unit Economics",
                metric="Net Margin (%)",
                current_value=ratios.net_margin_pct,
                target_value=8.0,
                rationale="Thin operating margins leave no margin of safety against market downturns or cost inflation.",
                action_plan=[
                    "Audit product/service lines for gross margin contribution and sunset negative-margin offerings.",
                    "Consolidate supplier purchasing to negotiate bulk volume discounts.",
                    "Automate manual back-office billing and fulfillment processes to reduce SG&A overhead."
                ]
            ))

        # 5. Interest Coverage
        if ratios.interest_coverage < 2.5:
            recommendations.append(RecommendationItem(
                id="rec-cov-1",
                category="Coverage",
                priority="High" if ratios.interest_coverage < 1.5 else "Medium",
                title="Hedge & Reduce Debt Servicing Burdens",
                metric="Interest Coverage Ratio",
                current_value=ratios.interest_coverage,
                target_value=3.5,
                rationale="A narrow interest coverage buffer creates high vulnerability if interest rates rise or operating income dips.",
                action_plan=[
                    "Engage lenders early to discuss covenant relief or extended amortization schedules.",
                    "Prioritize cash allocation to paying down the highest interest rate tranches.",
                    "Cap variable interest exposure with rate collar or swap hedges where applicable."
                ]
            ))

        # 6. Safe / General Maintenance if few issues
        if len(recommendations) == 0:
            recommendations.append(RecommendationItem(
                id="rec-gen-1",
                category="Growth & Resilience",
                priority="Low",
                title="Maintain Capital Discipline & Optimize Free Cash",
                metric="Overall Health Score",
                current_value=90.0,
                target_value=95.0,
                rationale="The company exhibits sound financial health across all primary ratios. Focus should remain on sustaining resilience.",
                action_plan=[
                    "Reinvest surplus cash into high-ROI expansion and research initiatives.",
                    "Maintain conservative debt boundaries (debt-to-equity below 1.2x).",
                    "Conduct quarterly stress testing against macroeconomic downside scenarios."
                ]
            ))

        return recommendations
